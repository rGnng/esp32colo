#!/usr/bin/env python3
"""Generate TFT_eSPI smooth-font arrays from the vendored, unmodified Inter 4.1.

Run with Pillow 12.0.0: .venv/bin/python scripts/generate_clock_fonts.py
Only regeneration needs Pillow; normal firmware builds use the checked-in header.
"""
from pathlib import Path
import hashlib
import math
import struct
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets/fonts/inter/InterVariable.ttf"
SOURCE_SHA256 = "4989b125924991b90d05b2d16e0e388c48f7d5bb8b30539bbf9c755278d0ccaf"
OUTPUT = ROOT / "firmware/include/inter_clock_fonts.h"


def encode(size, weight, characters, tabular=False):
    font = ImageFont.truetype(str(SOURCE), size)
    font.set_variation_by_axes([min(32, max(14, size)), weight])
    features = ["tnum"] if tabular else []
    metrics, bitmaps = [], []
    for ch in sorted(set(characters)):
        left, top, right, bottom = font.getbbox(ch, anchor="ls", features=features)
        width, height = right - left, bottom - top
        advance = math.floor(font.getlength(ch, features=features) + .5)
        assert 0 <= width <= 255 and 0 <= height <= 255 and 0 < advance <= 255
        assert -128 <= left <= 127
        image = Image.new("L", (width, height))
        ImageDraw.Draw(image).text((-left, -top), ch, font=font, fill=255,
                                   anchor="ls", features=features)
        metrics.append((ord(ch), height, width, advance, -top, left, 0))
        bitmaps.append(image.tobytes())
    ascent = max(m[4] for m in metrics)
    descent = max(0, max(m[1] - m[4] for m in metrics))
    result = struct.pack(">6I", len(metrics), 11, size, 0, ascent, descent)
    result += b"".join(struct.pack(">7i", *m) for m in metrics)
    return result + b"".join(bitmaps)


def main():
    assert hashlib.sha256(SOURCE.read_bytes()).hexdigest() == SOURCE_SHA256
    chunks = ["#pragma once\n#include <Arduino.h>\n\n"
              "// Generated by scripts/generate_clock_fonts.py from Inter 4.1 (OFL-1.1).\n"
              "// Original font and license: assets/fonts/inter/.\n"]
    for name, size, weight, chars, tabular in [
        ("kInterClock64", 64, 500, "-0123456789:", True),
        ("kInterClock18", 18, 400, "".join(chr(i) for i in range(33, 127)), False),
        ("kInterClock14", 14, 400, "".join(chr(i) for i in range(33, 127)), False),
    ]:
        data = encode(size, weight, chars, tabular)
        chunks.append(f"\nconst uint8_t {name}[] PROGMEM = {{\n")
        for start in range(0, len(data), 16):
            chunks.append("  " + ", ".join(f"0x{v:02x}" for v in data[start:start + 16]) + ",\n")
        chunks.append("};\n")
        print(f"{name}: {len(data)} bytes")
    OUTPUT.write_text("".join(chunks))


if __name__ == "__main__":
    main()
