#!/usr/bin/env python3
"""Offline 16px Japanese playback font and Iconify status bitmap.
Only regeneration needs Pillow/fontTools/CairoSVG; firmware uses checked-in data.
"""
from pathlib import Path
import hashlib,io,json,math,struct
from PIL import Image,ImageDraw,ImageFont
from fontTools.ttLib import TTFont
import cairosvg
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'assets/fonts/noto-sans-jp/NotoSansJP-Regular.otf'
SHA='dff723ba59d57d136764a04b9b2d03205544f7cd785a711442d6d2d085ac5073'
SIZE=16

def pack(image):
    pixels=[min(15,(value+8)//17) for value in image.getdata()]
    return bytes((pixels[i]<<4)|(pixels[i+1] if i+1<len(pixels) else 0) for i in range(0,len(pixels),2))

def main():
    assert hashlib.sha256(SOURCE.read_bytes()).hexdigest()==SHA
    points=sorted(TTFont(SOURCE).getBestCmap())
    font=ImageFont.truetype(str(SOURCE),SIZE)
    records=[];bitmaps=bytearray()
    for n,point in enumerate(points):
        char=chr(point);left,top,right,bottom=font.getbbox(char,anchor='ls')
        width,height=right-left,bottom-top;advance=math.floor(font.getlength(char)+.5)
        assert 0<=width<256 and 0<=height<256 and 0<=advance<256 and -128<=left<128 and -128<=top<128
        image=Image.new('L',(width,height));ImageDraw.Draw(image).text((-left,-top),char,font=font,fill=255,anchor='ls')
        records.append(struct.pack('<IIBBBbb3x',point,len(bitmaps),width,height,advance,left,top));bitmaps.extend(pack(image))
        if n%4000==0:print('Rasterized',n,'glyphs',flush=True)
    data=struct.pack('<4sII',b'CPF1',len(points),12+len(points)*16)+b''.join(records)+bitmaps
    svg=(ROOT/'assets/icons/andrsrxn/bluetooth-connecting.svg').read_bytes()
    png=cairosvg.svg2png(bytestring=svg.replace(b'currentColor',b'#ffffff'),output_width=32,output_height=32)
    icon=pack(Image.open(io.BytesIO(png)).convert('RGBA').getchannel('A'))
    out=['#pragma once\n#include <cstdint>\n#ifdef ARDUINO\n#include <pgmspace.h>\n#else\n#ifndef PROGMEM\n#define PROGMEM\n#endif\n#endif\n',
         '// Generated by scripts/generate_playback_font.py. Noto Sans JP 2.004 (OFL-1.1),\n// andrsrxn:bluetooth-connecting (MIT). Sources/licenses in assets/fonts/ and assets/icons/.\n',
         'namespace PlaybackAssets {\n']
    for name,values in [('kJapanese16',data),('kBluetoothConnecting32',icon)]:
        out.append(f'const uint8_t {name}[] PROGMEM = {{\n')
        for i in range(0,len(values),24):out.append(' '+','.join(f'0x{x:02x}' for x in values[i:i+24])+',\n')
        out.append('};\n')
    out.append(f'constexpr unsigned kGlyphCount={len(points)},kFontBytes={len(data)};\n}}\n')
    (ROOT/'firmware/include/playback_assets.h').write_text(''.join(out))
    manifest=dict(source_sha256=SHA,pixel_size=SIZE,glyphs=len(points),font_bytes=len(data),bitmap_bytes=len(bitmaps),format='CPF1 sorted 16-byte metrics + packed 4-bit coverage',icon='andrsrxn:bluetooth-connecting',icon_pixels=32,icon_bytes=len(icon))
    (ROOT/'assets/fonts/noto-sans-jp/manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps(manifest),flush=True)
if __name__=='__main__':main()
