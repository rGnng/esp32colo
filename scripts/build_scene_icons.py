#!/usr/bin/env python3
"""Optional host-only rebuild of 32 vendored SVGs into sprite/64px XBM assets."""
from pathlib import Path
import io,json,re
import cairosvg
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'firmware/web/vendor/bootstrap-icons'
names=json.loads((source/'icons.json').read_text())
labels=[name.replace('-',' ').title() for name in names]
header=['#pragma once','#include <Arduino.h>','// Generated by scripts/build_scene_icons.py; Bootstrap Icons 1.13.1, MIT.',
        'namespace SceneIcons {','constexpr int kCount=32,kSize=64;',
        'constexpr const char *kNames[] = {'+','.join(json.dumps(n) for n in names)+'};',
        'constexpr const char *kLabels[] = {'+','.join(json.dumps(n) for n in labels)+'};',
        'const uint8_t kBitmaps[32][512] PROGMEM = {']
symbols=[]
for name in names:
    svg=(source/'icons'/(name+'.svg')).read_text()
    body=re.search(r'<svg[^>]*>(.*)</svg>',svg,re.S).group(1)
    symbols.append('<symbol id="'+name+'" viewBox="0 0 16 16" fill="currentColor">'+body+'</symbol>')
    png=cairosvg.svg2png(bytestring=svg.replace('currentColor','#ffffff').encode(),output_width=64,output_height=64)
    alpha=Image.open(io.BytesIO(png)).convert('RGBA').getchannel('A')
    bits=[]
    for y in range(64):
        for x in range(0,64,8):bits.append(sum((1<<bit) for bit in range(8) if alpha.getpixel((x+bit,y))>=128))
    header.append('  { // '+name)
    for at in range(0,512,24):header.append('    '+','.join('0x%02x'%b for b in bits[at:at+24])+',')
    header.append('  },')
header+=['};','} // namespace SceneIcons','']
(ROOT/'firmware/include/scene_icons.h').write_text('\n'.join(header))
(ROOT/'firmware/web/scene-icons.svg').write_text('<svg xmlns="http://www.w3.org/2000/svg">'+''.join(symbols)+'</svg>\n')
print('Built 32 icon glyphs (16 KiB flash) and local SVG sprite.')
